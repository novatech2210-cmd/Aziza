# Write out to new_russian_pairs.jsonl
with open("new_russian_pairs.jsonl", "w", encoding="utf-8") as f:
    for p in pairs:
        f.write(json.dumps(p, ensure_ascii=False) + "\n")

print(f"Generated {len(pairs)} pairs in new_russian_pairs.jsonl")

# Now append these to aziza-bilingual.jsonl
try:
    with open("aziza-bilingual.jsonl", "a", encoding="utf-8") as out:
        for p in pairs:
            out.write(json.dumps(p, ensure_ascii=False) + "\n")
    print("Appended pairs to aziza-bilingual.jsonl")
except Exception as e:
    print("Warning: aziza-bilingual.jsonl not found or error appending:", e)

