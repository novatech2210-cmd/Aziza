    ("Какое расстояние от Земли до Луны?", "Среднее расстояние от Земли до Луны составляет около 384 400 километров. Свет преодолевает это расстояние примерно за 1,28 секунды."),
    ("Кто написал роман «Война и мир»?", "Роман-эпопея «Война и мир» был написан русским писателем Львом Николаевичем Толстым. Он работал над произведением с 1863 по 1869 год."),
    ("Что такое фотосинтез?", "Фотосинтез — это процесс, при котором растения, водоросли и некоторые бактерии преобразуют световую энергию в химическую. Они поглощают углекислый газ и воду, а с помощью света и хлорофилла производят глюкозу и выделяют кислород."),
    ("Какая столица у Японии?", "Столицей Японии является город Токио. Это один из крупнейших мегаполисов мира, расположенный на острове Хонсю.")
